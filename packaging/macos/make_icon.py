#!/usr/bin/env python3
"""Generate Roost icon PNGs and Rust tail constants from the canonical SVG."""
import argparse
import binascii
import math
import re
import struct
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

SIZE = 1024
SUPERSAMPLE = 2
SVG = Path("docs/design/roost-tail.svg")
RUST = Path("crates/roost-gui/src/identity_generated.rs")
ASSETS = Path("crates/roost-gui/assets")


def tag(e): return e.tag.rsplit("}", 1)[-1]
def rgb(value):
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value): raise ValueError(f"unsupported color {value}")
    return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5))
def nums(value): return [float(v) for v in re.findall(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?", value)]

def parse_svg(path):
    root = ET.parse(path).getroot()
    view = nums(root.attrib["viewBox"])
    if view[:2] != [0, 0] or len(view) != 4 or view[2] != view[3]: raise ValueError("expected square zero-origin viewBox")
    rect = next(e for e in root.iter() if tag(e) == "rect")
    group = next(e for e in root.iter() if tag(e) == "g")
    if group.attrib.get("fill") != "none" or group.attrib.get("stroke-linecap") != "round": raise ValueError("expected round unfilled path group")
    paths = []
    for e in group:
        if tag(e) != "path": continue
        values = nums(e.attrib["d"])
        if len(values) != 8 or not e.attrib["d"].lstrip().startswith("M") or "C" not in e.attrib["d"]: raise ValueError(f"expected M/C path: {e.attrib['d']}")
        paths.append((values, rgb(e.attrib["stroke"])))
    hub = next(e for e in root.iter() if tag(e) == "circle")
    return {"canvas": view[2], "radius": float(rect.attrib["rx"]), "background": rgb(rect.attrib["fill"]), "stroke": float(group.attrib["stroke-width"]), "paths": paths, "hub": (float(hub.attrib["cx"]), float(hub.attrib["cy"]), float(hub.attrib["r"]), rgb(hub.attrib["fill"]))}

def rust(data):
    c = data["canvas"]
    rows = ",\n    ".join(f"([{', '.join(f'{v:.1}' for v in p)}], [{col[0]}, {col[1]}, {col[2]}])" for p, col in data["paths"])
    bg, hub = data["background"], data["hub"]
    return f"// @generated by packaging/macos/make_icon.py from docs/design/roost-tail.svg; do not edit.\npub const CANVAS: f32 = {c:.1};\npub const CORNER_RADIUS: f32 = {data['radius']:.1};\npub const STROKE_WIDTH: f32 = {data['stroke']:.1};\npub const BACKGROUND: [u8; 3] = [{bg[0]}, {bg[1]}, {bg[2]}];\npub const HUB: ([f32; 2], f32, [u8; 3]) = ([{hub[0]:.1}, {hub[1]:.1}], {hub[2]:.1}, [{hub[3][0]}, {hub[3][1]}, {hub[3][2]}]);\npub const PATHS: [([f32; 8], [u8; 3]); {len(data['paths'])}] = [\n    {rows},\n];\n"

def cubic(t, a, b, c, d):
    q = 1 - t
    return (q**3*a[0] + 3*q*q*t*b[0] + 3*q*t*t*c[0] + t**3*d[0], q**3*a[1] + 3*q*q*t*b[1] + 3*q*t*t*c[1] + t**3*d[1])
def blend_disk(px, size, cx, cy, radius, color):
    x0, x1 = max(0, int(cx-radius-1)), min(size, int(cx+radius+2)); y0, y1 = max(0, int(cy-radius-1)), min(size, int(cy+radius+2)); rr=radius*radius
    for y in range(y0,y1):
        dy=y+.5-cy
        for x in range(x0,x1):
            if (x+.5-cx)**2+dy*dy <= rr:
                i=(y*size+x)*4; px[i:i+4]=bytes((*color,255))
def down(src, size, factor):
    out=bytearray(size*size*4); width=size*factor
    for y in range(size):
        for x in range(size):
            cells=[src[((y*factor+sy)*width+x*factor+sx)*4:((y*factor+sy)*width+x*factor+sx)*4+4] for sy in range(factor) for sx in range(factor)]
            i=(y*size+x)*4; out[i:i+4]=bytes(sum(c[k] for c in cells)//(factor*factor) for k in range(4))
    return out
def render(data):
    n=SIZE*SUPERSAMPLE; px=bytearray(n*n*4); scale=n/data["canvas"]; r=data["radius"]*scale
    # SVG rect: only its rounded interior is opaque; outer canvas corners remain transparent.
    for y in range(n):
        for x in range(n):
            cx=max(r,min(x+.5,n-r)); cy=max(r,min(y+.5,n-r))
            if (x+.5-cx)**2+(y+.5-cy)**2 <= r*r:
                i=(y*n+x)*4; px[i:i+4]=bytes((*data["background"],255))
    for values,color in data["paths"]:
        a,b,c,d=(values[0:2],values[2:4],values[4:6],values[6:8])
        for step in range(SIZE+1):
            x,y=cubic(step/SIZE,a,b,c,d); blend_disk(px,n,x*scale,y*scale,data["stroke"]*scale/2,color)
    x,y,radius,color=data["hub"]; blend_disk(px,n,x*scale,y*scale,radius*scale,color)
    big=down(px,SIZE,SUPERSAMPLE)
    return big, down(big,256,4)
def png(width,height,rgba):
    raw=b''.join(b'\0'+rgba[y*width*4:(y+1)*width*4] for y in range(height))
    def chunk(k,d): return struct.pack('>I',len(d))+k+d+struct.pack('>I',binascii.crc32(k+d)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',width,height,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(raw,9))+chunk(b'IEND',b'')
def outputs(root):
    data=parse_svg(root/SVG); big,small=render(data)
    return {root/RUST: rust(data).encode(), root/ASSETS/'icon-1024.png': png(SIZE,SIZE,big), root/ASSETS/'icon-256.png': png(256,256,small)}
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); args=ap.parse_args(); root=Path(__file__).resolve().parents[2]
    generated=outputs(root)
    stale=[p for p,b in generated.items() if not p.exists() or p.read_bytes()!=b]
    if args.check:
        if stale: raise SystemExit('generated Roost identity files are stale:\n'+'\n'.join(str(p.relative_to(root)) for p in stale))
        print('Roost identity assets are current'); return
    for p,b in generated.items(): p.write_bytes(b); print('wrote',p)
if __name__=='__main__': main()
